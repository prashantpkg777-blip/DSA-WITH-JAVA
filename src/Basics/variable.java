package Basics;

public class variable {
    static void main() {
        // inilatize
        int age = 18;
        System.out.println(age);

        // case sensitive
        int weight = 50;
        int WEIGHT = 60;
        System.out.println("weight:"+weight);
        System.out.println("Weight:"+WEIGHT);

        // main is not reversed keyword
        int main = 5;
        System.out.println(main);

    }
}
